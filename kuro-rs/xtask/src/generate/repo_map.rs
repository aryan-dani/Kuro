use std::fs;
use std::path::Path;

use crate::paths::repo_root;

pub fn run() -> i32 {
    let root = repo_root();
    let out = root.join("docs/REPO_MAP.md");
    let content = generate(&root);
    if let Err(e) = fs::write(&out, content) {
        eprintln!("gen repo_map: {e}");
        return 1;
    }
    eprintln!("gen: wrote {}", out.display());
    0
}

pub fn run_check() -> i32 {
    let root = repo_root();
    let out = root.join("docs/REPO_MAP.md");
    let expected = generate(&root);
    let current = fs::read_to_string(&out).unwrap_or_default();
    if current != expected {
        eprintln!("gen check: docs/REPO_MAP.md is stale (run `cargo xtask gen`)");
        return 1;
    }
    eprintln!("gen check: ok");
    0
}

pub fn generate(root: &Path) -> String {
    let mut lines = vec![
        "# Kuro repository map".to_string(),
        String::new(),
        "Generated by `cargo xtask gen`. Do not hand-edit.".to_string(),
        String::new(),
        "Kuro is a Windows desk voice agent: Rust engine in `kuro-rs/`, WinUI shell in".to_string(),
        "`KuroShell/`. Phase 11 introduced this map; deeper per-file detail arrives in later phases.".to_string(),
        String::new(),
        "## Rust workspace crates".to_string(),
        String::new(),
        "| Crate | Role |".to_string(),
        "|-------|------|".to_string(),
    ];
    let crates_dir = root.join("kuro-rs/crates");
    if let Ok(entries) = fs::read_dir(&crates_dir) {
        let mut names: Vec<String> = entries
            .flatten()
            .filter(|e| e.path().is_dir())
            .filter_map(|e| e.file_name().to_str().map(str::to_string))
            .collect();
        names.sort();
        for name in names {
            let role = crate_blurb(&crates_dir.join(&name));
            lines.push(format!("| `{name}` | {role} |"));
        }
    }
    lines.push(String::new());
    lines.push("## Other projects".to_string());
    lines.push(String::new());
    lines.push("| Path | Role |".to_string());
    lines.push("|------|------|".to_string());
    lines.push("| `KuroShell/` | WinUI shell, supervisor, HUD |".to_string());
    lines.push("| `kuro-rs/xtask/` | Gate, checks, scaffolders, generators |".to_string());
    lines.push("| `scripts/` | PowerShell smoke and install helpers |".to_string());
    lines.push(String::new());
    lines.push("## Plans".to_string());
    lines.push(String::new());
    lines.push("Execution phases live in `docs/plans/`. Read `docs/plans/README.md` for the index.".to_string());
    lines.push(String::new());
    let mut out = lines.join("\n");
    if !out.ends_with('\n') {
        out.push('\n');
    }
    out
}

fn crate_blurb(crate_dir: &Path) -> String {
    let readme = crate_dir.join("README.md");
    if let Ok(text) = fs::read_to_string(&readme) {
        for line in text.lines() {
            let t = line.trim();
            if !t.is_empty() && !t.starts_with('#') {
                return t.to_string();
            }
        }
    }
    "See crate README.".to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generate_lists_crates() {
        let root = repo_root();
        let doc = generate(&root);
        assert!(doc.contains("kuro-core"));
        assert!(doc.contains("cargo xtask gen"));
    }

    #[test]
    fn generate_is_stable_on_second_call() {
        let root = repo_root();
        let a = generate(&root);
        let b = generate(&root);
        assert_eq!(a, b);
    }
}
